// Turns one synthesised stack into a conventional OpenTofu root module:
//
//   terraform.tf   required_version + required_providers
//   backend.tf     the S3 backend
//   providers.tf   provider configuration
//   locals.tf      locals (if any)
//   <group>.tf     one file per concern (a `Group` construct), e.g. eks.tf
//   policies/*.json  large IAM documents, loaded with file()
//
// cdktn renders HCL for us (it knows which attributes are blocks); this module
// splits it by top-level block, normalises it to idiomatic HCL (bare
// references, meta-arguments first) and replaces the terraform block, which
// cdktn's HCL renderer gets wrong. `tofu fmt` does the final whitespace.
import { TerraformDataSource, TerraformResource, type TerraformStack } from "cdktn";
import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { BaseStack, Group } from "./stacks/base.ts";

export interface LayoutFile {
  path: string;
  content: string;
}

export interface Block {
  type: string; // resource | data | provider | locals | terraform | output | variable | module
  labels: string[];
  text: string;
}

const HEADER = (stack: string) =>
  `# Generated by cdktn from infra/src (stack "${stack}"). Do not edit: change the TypeScript and re-run \`make synth\`.\n\n`;

// --- lexing ------------------------------------------------------------------

/** Index just past the string literal that starts at `i` (text[i] === '"'), honouring escapes and ${...} nesting. */
function endOfString(text: string, i: number): number {
  let j = i + 1;
  while (j < text.length) {
    const c = text[j];
    if (c === "\\") j += 2;
    else if (c === '"') return j + 1;
    else if ((c === "$" || c === "%") && text[j + 1] === "{") j = endOfTemplate(text, j + 1);
    else j++;
  }
  throw new Error(`unterminated string at ${i}`);
}

/** Index just past the `}` matching the `{` at `i`, skipping nested strings. */
function endOfTemplate(text: string, i: number): number {
  let depth = 0;
  let j = i;
  while (j < text.length) {
    const c = text[j];
    if (c === '"') {
      j = endOfString(text, j);
      continue;
    }
    if (c === "{") depth++;
    if (c === "}" && --depth === 0) return j + 1;
    j++;
  }
  throw new Error(`unterminated template at ${i}`);
}

/** Index just past a heredoc that starts at `i` (`<<EOT` or `<<-EOT`). */
function endOfHeredoc(text: string, i: number): number {
  const m = /^<<-?([A-Za-z_][A-Za-z0-9_]*)\n/.exec(text.slice(i));
  if (!m) return i + 2;
  const close = new RegExp(`\\n[ \\t]*${m[1]}[ \\t]*(\\n|$)`, "g");
  close.lastIndex = i + m[0].length - 1;
  const end = close.exec(text);
  if (!end) throw new Error(`unterminated heredoc ${m[1]}`);
  return end.index + end[0].length - (end[1] === "\n" ? 1 : 0);
}

/** Split HCL into its top-level blocks. */
export function splitBlocks(hcl: string): Block[] {
  const blocks: Block[] = [];
  let i = 0;
  while (i < hcl.length) {
    const rest = hcl.slice(i);
    const ws = /^\s+/.exec(rest);
    if (ws) {
      i += ws[0].length;
      continue;
    }
    const head = /^([a-z_]+)((?:\s+"[^"]*")*)\s*\{/.exec(rest);
    if (!head) throw new Error(`unexpected top-level HCL at ${i}: ${rest.slice(0, 60)}`);
    const open = i + head[0].length - 1;
    let depth = 0;
    let j = open;
    while (j < hcl.length) {
      const c = hcl[j];
      if (c === '"') {
        j = endOfString(hcl, j);
        continue;
      }
      if (c === "<" && hcl[j + 1] === "<") {
        j = endOfHeredoc(hcl, j);
        continue;
      }
      if (c === "{") depth++;
      if (c === "}" && --depth === 0) break;
      j++;
    }
    const labels = [...head[2].matchAll(/"([^"]*)"/g)].map((m) => m[1]);
    blocks.push({ type: head[1], labels, text: hcl.slice(i, j + 1) });
    i = j + 1;
  }
  return blocks;
}

// --- normalisation -----------------------------------------------------------

/** `"${expr}"` → `expr` when the interpolation is the whole string (same value, same type in HCL). */
export function unwrapInterpolations(text: string): string {
  let out = "";
  let i = 0;
  while (i < text.length) {
    const c = text[i];
    if (c === "<" && text[i + 1] === "<") {
      const end = endOfHeredoc(text, i);
      out += text.slice(i, end);
      i = end;
      continue;
    }
    if (c !== '"') {
      out += c;
      i++;
      continue;
    }
    const end = endOfString(text, i);
    const literal = text.slice(i, end);
    if (literal.startsWith('"${') && endOfTemplate(text, i + 2) === end - 1) {
      out += unwrapInterpolations(literal.slice(3, -2));
    } else {
      out += literal;
    }
    i = end;
  }
  return out;
}

/** depends_on takes references, not strings: `"aws_iam_role.x",` → `aws_iam_role.x,`. */
function unquoteDependsOn(text: string): string {
  return text.replace(/depends_on\s*=\s*\[([^\]]*)\]/g, (_, body: string) => `depends_on = [${body.replace(/"([A-Za-z0-9_.\-]+)"/g, "$1")}]`);
}

/** Meta-arguments first: `for_each`/`count` (single- or multi-line) straight after the block header. */
function hoistMetaArguments(block: Block): string {
  if (block.type !== "resource" && block.type !== "data") return block.text;
  const lines = block.text.split("\n");
  const at = lines.findIndex((l, n) => n > 0 && /^\s*(for_each|count)\s*=/.test(l));
  if (at < 0) return block.text;
  let end = at;
  for (let depth = nesting(lines[at]); depth > 0; ) depth += nesting(lines[++end]);
  const meta = lines.splice(at, end - at + 1);
  lines.splice(1, 0, ...meta, "");
  return lines.join("\n");
}

/** Net bracket depth change of one line, ignoring brackets inside string literals. */
const nesting = (line: string) => {
  let d = 0;
  for (const c of line.replace(/"(?:[^"\\]|\\.)*"/g, "")) d += "[{(".includes(c) ? 1 : "]})".includes(c) ? -1 : 0;
  return d;
};

export function normalise(block: Block): string {
  return unwrapInterpolations(unquoteDependsOn(hoistMetaArguments(block)));
}

// --- terraform.tf / backend.tf ------------------------------------------------

const hclValue = (v: unknown): string => (typeof v === "string" ? JSON.stringify(v) : String(v));

function terraformFile(tf: any): string {
  const providers = Object.entries(tf.required_providers ?? {})
    .map(([name, p]: [string, any]) => `    ${name} = {\n      source  = ${hclValue(p.source)}\n      version = ${hclValue(p.version)}\n    }`)
    .join("\n");
  return `terraform {\n  required_version = ${hclValue(tf.required_version)}\n\n  required_providers {\n${providers}\n  }\n}\n`;
}

function backendFile(tf: any): string {
  const [[kind, cfg]] = Object.entries(tf.backend ?? {}) as [string, Record<string, unknown>][];
  const attrs = Object.entries(cfg)
    .map(([k, v]) => `    ${k} = ${hclValue(v)}`)
    .join("\n");
  return `terraform {\n  backend ${JSON.stringify(kind)} {\n${attrs}\n  }\n}\n`;
}

// --- layout ------------------------------------------------------------------

/** Which Group (file) each resource and data source belongs to, keyed by its HCL address. */
function groupsOf(stack: TerraformStack): { byAddress: Map<string, string>; order: string[] } {
  const byAddress = new Map<string, string>();
  const order: string[] = [];
  for (const c of stack.node.findAll()) {
    if (c instanceof Group && !order.includes(c.node.id)) order.push(c.node.id);
    if (!(c instanceof TerraformResource || c instanceof TerraformDataSource)) continue;
    const group = c.node.scopes.find((s) => s instanceof Group)?.node.id ?? "main";
    const kind = c instanceof TerraformDataSource ? "data" : "resource";
    byAddress.set(`${kind}.${c.terraformResourceType}.${c.friendlyUniqueId}`, group);
  }
  return { byAddress, order };
}

export interface LayoutOptions {
  /** Extra files the stack owns, relative to its directory (e.g. policies/*.json). */
  files?: Map<string, string>;
}

export function layout(stack: TerraformStack, options: LayoutOptions = {}): LayoutFile[] {
  const id = stack.node.id;
  const json = stack.toTerraform();
  const { byAddress, order } = groupsOf(stack);
  const buckets = new Map<string, string[]>();
  const put = (file: string, text: string) => buckets.set(file, [...(buckets.get(file) ?? []), text]);

  for (const block of splitBlocks(stack.toHclTerraform().hcl)) {
    switch (block.type) {
      case "terraform":
        break; // regenerated below from the JSON synth, which is correct
      case "provider":
        put("providers.tf", normalise(block));
        break;
      case "locals":
        put("locals.tf", normalise(block));
        break;
      case "variable":
        put("variables.tf", normalise(block));
        break;
      case "output":
        put("outputs.tf", normalise(block));
        break;
      case "resource":
      case "data": {
        const group = byAddress.get(`${block.type}.${block.labels[0]}.${block.labels[1]}`) ?? "main";
        put(`${group}.tf`, normalise(block));
        break;
      }
      default:
        put("main.tf", normalise(block));
    }
  }

  const files: LayoutFile[] = [
    { path: "terraform.tf", content: terraformFile(json.terraform) },
    { path: "backend.tf", content: backendFile(json.terraform) },
  ];
  const fixed = ["providers.tf", "variables.tf", "locals.tf"];
  const concerns = [...order.map((g) => `${g}.tf`), "main.tf", "outputs.tf"];
  for (const name of [...fixed, ...concerns]) {
    const texts = buckets.get(name);
    if (texts) files.push({ path: name, content: texts.join("\n\n") + "\n" });
  }
  for (const [path, content] of options.files ?? []) files.push({ path, content });
  return files.map((f) => (f.path.endsWith(".tf") ? { ...f, content: HEADER(id) + f.content } : f));
}

// --- writing -----------------------------------------------------------------

/**
 * Write each stack as a conventional OpenTofu root module under
 * `<outdir>/tofu/<stack>/`, then `tofu fmt` it. Runs inside `cdktn synth`
 * (main.ts). `<outdir>/stacks/` keeps cdktn's own single-file JSON, which the
 * cdktn CLI reads; we plan and apply from `tofu/`, never from `stacks/`.
 */
export function writeLayout(outdir: string, stacks: TerraformStack[], format = true): void {
  for (const stack of stacks) {
    const dir = join(outdir, "tofu", stack.node.id);
    rmSync(dir, { recursive: true, force: true });
    const files = stack instanceof BaseStack ? stack.files : undefined;
    for (const f of layout(stack, { files })) {
      mkdirSync(dirname(join(dir, f.path)), { recursive: true });
      writeFileSync(join(dir, f.path), f.content);
    }
    if (format) execFileSync("tofu", ["fmt", "-list=false", dir], { stdio: "inherit" });
  }
}
